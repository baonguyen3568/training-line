"""Isolated app server for the M1 E2E (tier "app"): real FastAPI + executor + FakeWorker, temp workspace.

Never touches the developer app (:7870/:7875) or the real outputs/: the workspace is a fresh temp dir and the
frontend is served from a separate build dir. Token comes from E2E_TOKEN (test-only, generated by e2e.sh).
Usage: E2E_TOKEN=... uv run python scripts/qa/e2e_app.py <port> <static_dir>
"""

from __future__ import annotations

import os
import shutil
import sys
import tempfile
from pathlib import Path


def main() -> int:
    import uvicorn

    from vlm_pipeline.app.main import create_app
    from vlm_pipeline.app.services import DefaultServices
    from vlm_pipeline.nodes import REGISTRY

    port, static_dir = int(sys.argv[1]), Path(sys.argv[2]).resolve()
    token = os.environ["E2E_TOKEN"]
    with tempfile.TemporaryDirectory(prefix="vlm-e2e-") as tmp:
        # Templates live in the repo (configs/templates); the temp workspace gets a copy so the gallery is real.
        repo = Path(__file__).resolve().parents[2]
        shutil.copytree(repo / "configs" / "templates", Path(tmp) / "configs" / "templates")
        services = DefaultServices(registry=REGISTRY, root=Path(tmp), worker="fake")
        # e2e.sh runs this tier while GPU jobs may hold the lock: it must never get a real (lock-taking) worker.
        if services.worker != "fake":
            raise SystemExit(f"e2e app tier must run on FakeWorker, got worker={services.worker!r}")
        app = create_app(services, token=token, port=port, static_dir=static_dir)
        uvicorn.run(app, host="127.0.0.1", port=port, log_level="warning", access_log=False)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
