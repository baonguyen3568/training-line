"""Spec tests for third-party node (plugin) sandboxing: P003 D16 + P009 §2.4 (ADR-009).

ASSUMED INTERFACE (draft - agree with bao-backend/bao-security, rename both sides together):
- ``vlm_pipeline.plugins.manifest.check_manifest(manifest: dict) -> list[str]``: blocking reason codes from the
  D16 table ("Lý do chặn cài"): ``manifest_invalid``, ``hash_unpinned``, ``permission_unsupported``, ...
  Empty list = installable. Never raises on bad input.
- ``vlm_pipeline.plugins.manifest.load_nodespec(manifest: dict) -> NodeSpecResult`` with ``spec`` and ``codes``.
- ``vlm_pipeline.plugins.sandbox.docker_args(manifest: dict, run_dir: Path) -> list[str]``: args generated by the
  orchestrator from the fixed permission table (manifest can never inject flags).
- ``vlm_pipeline.plugins.sandbox.validate_outputs(out_dir: Path) -> list[str]``: rejection codes for ``/out``.
  ALLOWLIST by parsing (bao-security): a file passes only if it parses as its declared format - json/jsonl
  (``json.loads`` per line), safetensors (8-byte LE header length + valid JSON header), parquet (``PAR1`` at head
  and tail), image/video (decodes, within pixel/size limits). Everything else is rejected; pickle magic checks are
  kept only as regression cases (protocol 0/1 pickles are text and have no 0x80 magic).
- ``vlm_pipeline.plugins.sandbox.check_image_digest(installed: str, current: str) -> list[str]``.
- ``vlm_pipeline.plugins.install.needs_reapproval(old_manifest, new_manifest, *, old_trust, new_trust) -> bool``;
  trust in ``first_party | reviewed | unverified``.
- ``vlm_pipeline.plugins.names``: ``name_lookalike_of(name, known) -> str | None``,
  ``check_display_name(text) -> list[str]`` (empty = ok), ``display_names_equal(a, b) -> bool`` (NFC-normalised).
  Identifier rule per segment (publisher, pack, node name): ``^[a-z0-9][a-z0-9_.-]{0,63}$``.
- ``vlm_pipeline.plugins.install.confirmation_level(trust: str, permissions: dict) -> "none"|"checkbox"|"type_name"``.
"""

