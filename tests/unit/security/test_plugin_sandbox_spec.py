# ---------------------------------------------------------------------- docker args (T1-T5)
@pytest.mark.parametrize("gpu", [False, True])
def test_docker_args_never_escalate(tmp_path: Path, gpu: bool) -> None:
    from vlm_pipeline.plugins.sandbox import docker_args

    args = docker_args(_with("permissions.gpu", gpu), tmp_path)
    joined = " ".join(args)
    assert "--privileged" not in joined
    assert "--network host" not in joined
    assert "--network=host" not in joined
    assert ("--network none" in joined) or ("--network=none" in joined)
    assert "--read-only" in args
    assert any(a.startswith("--cap-drop") for a in args)
    assert any("no-new-privileges" in a for a in args)
    assert any(a.startswith("61001:") or a.startswith("--user=61001:") for a in args), args
    assert ("--gpus" in joined) is gpu


def test_docker_args_mount_only_in_ro_and_out(tmp_path: Path) -> None:
    from vlm_pipeline.plugins.sandbox import docker_args

    args = docker_args(VALID, tmp_path)
    mounts = [args[i + 1] for i, a in enumerate(args) if a in ("-v", "--volume", "--mount")]
    mounts += [a.split("=", 1)[1] for a in args if a.startswith(("--volume=", "--mount="))]
    assert len(mounts) == 2, mounts
    in_mounts = [m for m in mounts if "/in" in m.replace("/input", "")]
    out_mounts = [m for m in mounts if "/out" in m]
    assert len(in_mounts) == 1, mounts
    assert len(out_mounts) == 1, mounts
    assert ":ro" in in_mounts[0] or "readonly" in in_mounts[0], mounts
    assert ":ro" not in out_mounts[0], mounts


def test_docker_args_pass_no_host_env_or_secret(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    from vlm_pipeline.plugins.sandbox import docker_args

    monkeypatch.setenv("HF_TOKEN", "hf_" + "s" * 34)
    monkeypatch.setenv("NGC_API_KEY", "nvapi-" + "k" * 40)
    joined = " ".join(docker_args(VALID, tmp_path))
    assert "HF_TOKEN" not in joined
    assert "NGC_API_KEY" not in joined
    assert "hf_" not in joined
    assert "--env-file" not in joined


