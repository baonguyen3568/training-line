SHA = "a" * 40
DIGEST = "sha256:" + "b" * 64

VALID: dict[str, Any] = {
    "permissions": {"gpu": False, "network": "none", "max_runtime": "1h", "max_memory": "8GiB"},
    "origin": {
        "publisher": "acme",
        "package": "acme/ocr-tools",
        "version": "1.0.0",
        "source_repo": "https://github.com/acme/ocr-tools",
        "commit_sha": SHA,
        "source_sha256": "c" * 64,
        "image_digest": DIGEST,
        "license": "Apache-2.0",
    },
}


def _check(manifest: Any) -> list[str]:
    from vlm_pipeline.plugins.manifest import check_manifest

    return check_manifest(manifest)


def _with(path: str, value: Any) -> dict[str, Any]:
    m = copy.deepcopy(VALID)
    *parents, leaf = path.split(".")
    node = m
    for p in parents:
        node = node[p]
    node[leaf] = value
    return m


